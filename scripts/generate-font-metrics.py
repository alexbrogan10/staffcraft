"""Writes src/worksheet/fontMetrics.ts from the subset fonts in public/fonts.

Run after changing the fonts:  pip install fonttools && python3 scripts/generate-font-metrics.py
"""

from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = {
    "regular": ROOT / "public/fonts/DejaVuSans-subset.ttf",
    "bold": ROOT / "public/fonts/DejaVuSans-Bold-subset.ttf",
}


def widths(path: Path) -> dict[int, float]:
    font = TTFont(path)
    units = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    return {cp: round(hmtx[name][0] / units, 4) for cp, name in sorted(cmap.items())}


def main() -> None:
    lines = [
        "// Generated by scripts/generate-font-metrics.py. Do not edit by hand.",
        "// Advance widths in ems for each code point in the subset worksheet fonts.",
        "",
        "export const FONT_WIDTHS = {",
    ]
    for weight, path in FONTS.items():
        table = widths(path)
        entries = ", ".join(f"{cp}: {w}" for cp, w in table.items())
        lines.append(f"  {weight}: {{ {entries} }} as Readonly<Record<number, number>>,")
    lines.append("} as const;")
    lines.append("")
    (ROOT / "src/worksheet/fontMetrics.ts").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
